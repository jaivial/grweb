#!/usr/bin/env node
// Publishes the static media of the public web to the GR Cup Bunny zone under content-hashed paths and writes the
// manifest the web reads (projects/ui/src/lib/cdn-manifest.ts).
//
//   set -a; . ~/grcup-dev/bunny-grcup.env; set +a      # BUNNY_GRCUP_STORAGE_ZONE/_KEY/_ENDPOINT/_PULL_URL (+ _PREFIX)
//   node scripts/cdn-publicar.mjs [--media <dir>]      # --media: extra files that only live on the CDN (videos)
//
// Each file goes to <prefix>/static/<sha256[:12]>/<name>: a new content is a new URL, so the CDN and the browsers can
// keep it forever (no purge). Files already on the CDN are skipped (HEAD 200). The storage key is only sent to Bunny.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';

const raiz = join(import.meta.dirname, '..');
const publico = join(raiz, 'projects/public/public');
const salida = join(raiz, 'projects/ui/src/lib/cdn-manifest.ts');

const env = (k) => (process.env[k] ?? '').trim();
const zona = env('BUNNY_GRCUP_STORAGE_ZONE'), clave = env('BUNNY_GRCUP_STORAGE_KEY'), pull = env('BUNNY_GRCUP_PULL_URL');
const prefijo = (env('BUNNY_GRCUP_PREFIX') || 'grcup').replace(/^\/+|\/+$/g, '');
const host = new URL(env('BUNNY_GRCUP_STORAGE_ENDPOINT') || 'https://storage.bunnycdn.com').host;
if (!zona || !clave || !pull) {
  console.error('Faltan BUNNY_GRCUP_STORAGE_ZONE, BUNNY_GRCUP_STORAGE_KEY o BUNNY_GRCUP_PULL_URL en el entorno.');
  process.exit(2);
}
const base = `${pull.replace(/\/+$/, '')}/${prefijo}`;

const TIPOS = { webp: 'image/webp', avif: 'image/avif', jpg: 'image/jpeg', png: 'image/png', mp4: 'video/mp4', webm: 'video/webm' };
const listar = (dir) => readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? listar(join(dir, n)) : [join(dir, n)]));

// Key = the path the code uses: «/img/…» for the files of public/ (local fallback), «/media/<name>» for --media.
const entradas = listar(join(publico, 'img')).map((f) => ['/' + relative(publico, f), f]);
const i = process.argv.indexOf('--media');
if (i > 0) entradas.push(...listar(process.argv[i + 1]).map((f) => ['/media/' + basename(f), f]));

const files = {};
let subidos = 0;
for (const [clavePath, f] of entradas.sort()) {
  const ext = f.split('.').pop().toLowerCase();
  if (!TIPOS[ext]) continue;
  const datos = readFileSync(f);
  const hash = createHash('sha256').update(datos).digest('hex').slice(0, 12);
  const ruta = `static/${hash}/${basename(f)}`;
  files[clavePath] = ruta;
  if ((await fetch(`${base}/${ruta}`, { method: 'HEAD' })).ok) continue;
  const r = await fetch(`https://${host}/${zona}/${prefijo}/${ruta}`, { method: 'PUT', headers: { AccessKey: clave, 'Content-Type': TIPOS[ext] }, body: datos });
  if (!r.ok) throw new Error(`subida ${clavePath}: HTTP ${r.status}`);
  subidos++;
}

writeFileSync(
  salida,
  `// Generated by scripts/cdn-publicar.mjs: do not edit. Path used by the code → content-hashed path on the CDN.\n` +
    `export const CDN_MANIFEST: { base: string; files: Record<string, string> } = ${JSON.stringify({ base, files }, null, 2)};\n`,
);
console.log(`${Object.keys(files).length} ficheros en el manifiesto, ${subidos} subidos; base ${base}`);
