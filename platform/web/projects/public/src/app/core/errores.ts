/** English text of a known API code (undefined if unknown). */
export const errorEn = (code: string | undefined): string | undefined => (code ? EN[code] : undefined);

/** Text to show for an API error: ES → backend detail (or def); EN → mapped code, 429 text, or def. */
export function textoError(e: unknown, def: string, lang: Lang = idiomaActual()): string {
  if (!(e instanceof HttpErrorResponse)) return def;
  const b = e.error as { code?: string; detail?: string } | null;
  if (lang !== 'en') return b?.detail || def;
  return errorEn(b?.code) ?? (e.status === 429 ? EN['DEMASIADAS_PETICIONES'] : def);
}
